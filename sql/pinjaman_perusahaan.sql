-- Rancangan soal 1. Database terpisah dari perpustakaan.
-- Nominal dalam rupiah utuh.

CREATE DATABASE IF NOT EXISTS pinjaman_perusahaan
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE pinjaman_perusahaan;

DROP TABLE IF EXISTS TBL_CICILAN;
DROP TABLE IF EXISTS TBL_PEMAKAIAN_DANA;
DROP TABLE IF EXISTS TBL_PENARIKAN_DANA;
DROP TABLE IF EXISTS TBL_TRANSFER_DANA;
DROP TABLE IF EXISTS TBL_PINJAMAN;
DROP TABLE IF EXISTS TBL_KARYAWAN;

CREATE TABLE TBL_KARYAWAN (
  ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
  NOMOR_INDUK VARCHAR(20) NOT NULL,
  NAMA VARCHAR(100) NOT NULL,
  PRIMARY KEY (ID),
  UNIQUE KEY uniq_karyawan_nomor_induk (NOMOR_INDUK)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE TBL_PINJAMAN (
  ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ID_KARYAWAN INT UNSIGNED NOT NULL,
  NOMOR_PINJAMAN VARCHAR(20) NOT NULL,
  TGL_PINJAMAN DATE NOT NULL,
  POKOK BIGINT UNSIGNED NOT NULL,
  PRIMARY KEY (ID),
  UNIQUE KEY uniq_pinjaman_nomor (NOMOR_PINJAMAN),
  KEY idx_pinjaman_karyawan (ID_KARYAWAN),
  CONSTRAINT fk_pinjaman_karyawan
    FOREIGN KEY (ID_KARYAWAN) REFERENCES TBL_KARYAWAN (ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE TBL_TRANSFER_DANA (
  ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ID_PINJAMAN INT UNSIGNED NOT NULL,
  TAHAP SMALLINT UNSIGNED NOT NULL,
  TGL_TRANSFER DATE NOT NULL,
  NOMINAL BIGINT UNSIGNED NOT NULL,
  REKENING_TUJUAN VARCHAR(30) NOT NULL,
  NAMA_BANK VARCHAR(50) NOT NULL,
  PRIMARY KEY (ID),
  UNIQUE KEY uniq_transfer_tahap (ID_PINJAMAN, TAHAP),
  KEY idx_transfer_pinjaman (ID_PINJAMAN),
  CONSTRAINT fk_transfer_pinjaman
    FOREIGN KEY (ID_PINJAMAN) REFERENCES TBL_PINJAMAN (ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE TBL_PENARIKAN_DANA (
  ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ID_TRANSFER INT UNSIGNED NOT NULL,
  TGL_PENARIKAN DATE NOT NULL,
  NOMINAL BIGINT UNSIGNED NOT NULL,
  PRIMARY KEY (ID),
  KEY idx_penarikan_transfer (ID_TRANSFER),
  CONSTRAINT fk_penarikan_transfer
    FOREIGN KEY (ID_TRANSFER) REFERENCES TBL_TRANSFER_DANA (ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE TBL_PEMAKAIAN_DANA (
  ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ID_PINJAMAN INT UNSIGNED NOT NULL,
  TGL_PEMAKAIAN DATE NOT NULL,
  NOMINAL BIGINT UNSIGNED NOT NULL,
  KEPERLUAN VARCHAR(200) NOT NULL,
  PRIMARY KEY (ID),
  KEY idx_pemakaian_pinjaman (ID_PINJAMAN),
  CONSTRAINT fk_pemakaian_pinjaman
    FOREIGN KEY (ID_PINJAMAN) REFERENCES TBL_PINJAMAN (ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE TBL_CICILAN (
  ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ID_PINJAMAN INT UNSIGNED NOT NULL,
  ANGSURAN_KE SMALLINT UNSIGNED NOT NULL,
  TGL_CICILAN DATE NOT NULL,
  NOMINAL BIGINT UNSIGNED NOT NULL,
  PRIMARY KEY (ID),
  UNIQUE KEY uniq_cicilan_angsuran (ID_PINJAMAN, ANGSURAN_KE),
  KEY idx_cicilan_pinjaman (ID_PINJAMAN),
  CONSTRAINT fk_cicilan_pinjaman
    FOREIGN KEY (ID_PINJAMAN) REFERENCES TBL_PINJAMAN (ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

