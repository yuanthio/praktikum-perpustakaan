-- Data awal perpustakaan. Tanggal soal dd/mm/yyyy disimpan sebagai DATE.
-- Kolom NIK pada soal disimpan sebagai NIS.

CREATE DATABASE IF NOT EXISTS perpustakaan
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE perpustakaan;

DROP TABLE IF EXISTS TBL_PINJAM;
DROP TABLE IF EXISTS TBL_BUKU;
DROP TABLE IF EXISTS TBL_SISWA;

CREATE TABLE TBL_SISWA (
  NIS CHAR(3) NOT NULL,
  NAMA VARCHAR(100) NOT NULL,
  TGL_LAHIR DATE NOT NULL,
  KELAMIN CHAR(1) NOT NULL,
  PRIMARY KEY (NIS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE TBL_BUKU (
  ID CHAR(4) NOT NULL,
  JUDUL VARCHAR(150) NOT NULL,
  ISBN VARCHAR(20) NOT NULL,
  PENGARANG VARCHAR(100) NOT NULL,
  PRIMARY KEY (ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE TBL_PINJAM (
  ID CHAR(4) NOT NULL,
  TGL_PINJAM DATE NOT NULL,
  TGL_BATAS DATE NOT NULL,
  TGL_KEMBALI DATE NULL,
  STATUS TINYINT UNSIGNED NOT NULL,
  NIS CHAR(3) NOT NULL,
  ID_BUKU CHAR(4) NOT NULL,
  PRIMARY KEY (ID),
  KEY idx_pinjam_nis (NIS),
  KEY idx_pinjam_buku (ID_BUKU),
  KEY idx_pinjam_status (STATUS),
  CONSTRAINT fk_pinjam_siswa
    FOREIGN KEY (NIS) REFERENCES TBL_SISWA (NIS),
  CONSTRAINT fk_pinjam_buku
    FOREIGN KEY (ID_BUKU) REFERENCES TBL_BUKU (ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

